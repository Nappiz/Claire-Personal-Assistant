from typing import Any, Protocol


class MemoryTransaction(Protocol):
    def new_message(self, **values: Any) -> Any: ...
    def new_conversation(self, **values: Any) -> Any: ...
    def new_outbox(self, **values: Any) -> Any: ...
    def new_usage(self, **values: Any) -> Any: ...
    def add(self, record: Any) -> None: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...
    def refresh(self, record: Any) -> None: ...
    def flush(self) -> None: ...
    def expire_all(self) -> None: ...
    def close(self) -> None: ...
    def get_session_history_messages(self, limit: Any, session_id: Any) -> Any: ...
    def get_session_summary_row(self, session_id: Any) -> Any: ...
    def resolve_project_scope_projects(self) -> Any: ...
    def filter_active_vector_memories_active_ids(self, message_ids: Any) -> Any: ...


class MemoryPersistence(Protocol):
    def open(self) -> MemoryTransaction: ...
    def wrap(self, db: Any) -> MemoryTransaction: ...
